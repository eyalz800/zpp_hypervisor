/**
 * The table is indexed by arithmetic on the character, so it is only
 * correct for as long as it stays aligned with ASCII. Checked here rather
 * than trusted: an entry inserted or dropped by hand would shift every
 * glyph after it, and the result would be a screen full of the wrong
 * letters at the one moment nothing else is readable.
 */
static_assert(font::glyph_count == 95);
static_assert(font::rows(' ')[0] == 0x00);
static_assert(font::rows(' ')[3] == 0x00);
// The crossbar of an A, the row that spans all five columns.
static_assert(font::rows('A')[3] == 0xf8);
// A zero has a diagonal through it, so its middle row is not symmetric.
static_assert(font::rows('0')[3] == 0xa8);
// Out of range folds to the question mark rather than reading past the
// end.
static_assert(font::rows('\n') == font::rows('?'));
static_assert(font::rows(static_cast<char>(0x7f)) == font::rows('?'));
// Nothing may be drawn in the last three columns or the last row, since
// that is where the spacing between characters and between lines comes
// from. Without it the renderer would have to add spacing itself, and
// every glyph would need checking by eye instead.
static_assert([] {
    for (std::size_t glyph{}; glyph < font::glyph_count; ++glyph) {
        if (font::glyphs[glyph][font::cell_height - 1]) {
            return false;
        }
        for (std::size_t row{}; row < font::cell_height; ++row) {
            if (font::glyphs[glyph][row] & 0x07) {
                return false;
            }
        }
    }
    return true;
}());

